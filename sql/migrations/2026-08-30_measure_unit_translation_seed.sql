-- Gives measure_unit_translation the provenance columns food_translation
-- already carries, then seeds it for the app's eight non-English locales.
--
-- The table has existed since the initial schema and has never held a row.
-- That was invisible until it was not: the app began showing a food's own
-- household measure as the unit on the bulk-add row, and because
-- food_summary.serving_size is built straight from
-- food_portion.portion_description with no translation join, a German row
-- read "3 slice". Measured against production before this ran:
-- food_portion 36,682 rows, food_portion_translation 0, this table 0,
-- food_translation 20,834 -- so food *names* were translated and their
-- units were not, which is why the gap read as correct.
-- App issue simonoppowa/OpenNutriTracker#864.
--
-- These translations are MACHINE-PRODUCED and are inserted as such:
-- source = 'machine', ai_generated = true, matching the vocabulary
-- AGENTS.md already defines for food_translation. The app is expected to
-- show only rows a human has promoted to 'verified'; until then every
-- locale keeps falling back to its own word for "serving", which is what it
-- shows today and has never been wrong.
--
-- Where a reviewer should look first. These English names are ambiguous out
-- of context and the record does not say which sense applies, so the guess
-- here is the least trustworthy part of the file:
--
--   cup      -- the 240 ml measure, or a drinking vessel
--   slice    -- bread (de: Scheibe) or cake (de: Stueck)
--   leg      -- poultry (de: Keule) or the anatomical sense
--   back, skin, shell, head, chunk, stalk, spear, rack, stick, bar
--   link/links, order, contents, unit, each, piece/pieces
--
-- Seven names are deliberately absent, being FDC bookkeeping rather than
-- anything a person would read: paired cooked w, paired raw w, dripping w,
-- orig ckd g, orig rw g, RACC, undetermined. 'undetermined' already becomes
-- 'portion' in food_summary.
--
-- on conflict do nothing, so re-running never overwrites a row a reviewer
-- has promoted to 'verified'.
--
-- Safe to run before any app change: nothing reads this table yet.
--
-- Run with: psql "" -f sql/migrations/2026-08-30_measure_unit_translation_seed.sql

