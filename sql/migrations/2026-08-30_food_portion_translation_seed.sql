-- Gives food_portion_translation the provenance columns food_translation
-- already carries, then seeds it for the app's eight non-English locales.
--
-- The table has existed since the initial schema and has never held a row,
-- so `food_summary.serving_size` -- built straight from
-- `food_portion.portion_description` with no translation join -- is English
-- for every locale the app ships. A German row read "3 slice".
-- App issue simonoppowa/OpenNutriTracker#864.
--
-- Why this table and not measure_unit_translation, which was seeded first:
-- `measure_unit` turned out to be 'undetermined' for 36,495 of 36,682
-- portions, so translating it reaches 0.5% of the data. The household word
-- people actually see lives in `portion_description`. That column looked
-- untranslatable at 36,682 rows, but the rows repeat heavily -- only 1,134
-- distinct usable values, and "1 cup" alone accounts for 3,056 portions.
--
-- Seeds the 109 most common values, covering 11,588 of the 15,441 portions
-- that carry a usable description -- 75%. The insert joins on the text, so
-- the 872 pairs below fan out to roughly 92,700 rows. The 85% and 90% cuts
-- are 201 and 287 values; the tail is deliberately left for a second pass,
-- once a locale has been through review once and the effort is known.
--
-- Excluded on purpose: 65 distinct values that are FDC survey bookkeeping
-- rather than anything a person reads -- "1 cup, NFS", "1 oz yields",
-- "1 breast, NS as to size", "Guideline amount per fl oz of beverage".
-- They cover 1,280 portions and are poor UI in English too, so those rows
-- keep falling back rather than being rendered faithfully into eight
-- languages.
--
-- These translations are MACHINE-PRODUCED and inserted as such:
-- source = 'machine', ai_generated = true, matching what AGENTS.md defines
-- for food_translation. The app is expected to show only rows a human has
-- promoted to 'verified'; until then every locale keeps falling back to its
-- own word for "serving", which is what it shows today.
--
-- Where a reviewer should look first:
--
--   1 slice        -- bread (de: Scheibe) or cake (de: Stueck)
--   1 cup          -- the 240 ml measure, or a drinking vessel
--   1 large, 1 small, 1 medium, 1 thick, 1 thin
--                  -- a bare adjective, so gender and ending depend on the
--                     food it qualifies, which this row does not know
--   1 regular      -- "regular" as a size, not as "ordinary"
--   1 submarine    -- a sandwich shape with no common word in most locales
--   1 sharing/movie theater size, 1 large/king size
--                  -- US retail sizes with no local equivalent
--
-- Brand names are left untranslated ("Spaghettio's"), and inch marks are
-- kept as published (5-7" diameter).
--
-- on conflict do nothing, so re-running never overwrites a row a reviewer
-- has promoted to 'verified'.
--
-- Safe to run before any app change: nothing reads this table yet.
--
-- Run with:
--   psql "$SUPABASE_DB_URL" -f sql/migrations/2026-08-30_food_portion_translation_seed.sql

