-- ============================================================
-- Multi-source food schema for Supabase
-- Matches multisource_food_schema.mermaid:
--   FDC (Foundation, SR Legacy, FNDDS Survey) + BLS 4.0 + INDB,
--   images, aliases, tags, i18n.
-- Run with: supabase db push / psql "$SUPABASE_DB_URL" -f schema.sql
--
-- Load order for the generated CSVs (fdc_to_ont_csv.py,
-- bls_to_ont_csv.py, indb_to_ont_csv.py):
--   food_source, nutrient, nutrient_mapping, food_category, food,
--   food_nutrient, measure_unit, food_portion, market_acquisition,
--   input_food, food_component, retention_factor, food_image,
--   food_alias
-- then: REFRESH MATERIALIZED VIEW food_summary;
-- ============================================================

-- ---------- 1. Source registry ------------------------------

create table if not exists food_source (
    code          text primary key,          -- fdc_foundation | fdc_sr_legacy | bls
    name          text not null,
    license_note  text
);

-- ---------- 2. Canonical core -------------------------------

create table if not exists food_category (
    id           int  primary key,
    source       text references food_source (code),  -- null = canonical
    description  text not null
);

create table if not exists food (
    id                bigint primary key,
    source            text   not null references food_source (code),
    source_code       text   not null,               -- fdc_id | BLS code
    description       text   not null,               -- full English name
    short_title       text,                          -- concise display name
    food_category_id  int    references food_category (id),
    publication_date  date,
    unique (source, source_code)
);

create table if not exists nutrient (
    id         int     primary key,   -- canonical app nutrient list
    name       text    not null,
    unit_name  text    not null,      -- G | MG | UG | KCAL
    rank       numeric
);

-- Import-time mapping: source component code -> canonical nutrient.
-- `source` is the import FAMILY (fdc | bls | indb), NOT a
-- food_source.code: 'fdc' covers fdc_foundation / fdc_sr_legacy /
-- fdc_survey, so there is deliberately no FK here.
-- No FK on source_component_code either: it references FDC nutrient
-- ids, BLS component codes, INDB column names depending on source.
create table if not exists nutrient_mapping (
    source                 text    not null,
    source_component_code  text    not null,
    nutrient_id            int     not null references nutrient (id),
    unit_factor            numeric not null default 1,
    primary key (source, source_component_code)
);

create table if not exists food_nutrient (
    id           bigint  primary key,
    food_id      bigint  not null references food (id) on delete cascade,
    nutrient_id  int     not null references nutrient (id),
    amount       numeric not null,    -- per 100 g, canonical unit
    origin       text,                -- analysis | calculated | label | literature
    reference    text,
    data_points  int,
    min          numeric,
    max          numeric,
    unique (food_id, nutrient_id)
);

create table if not exists measure_unit (
    id    int  primary key,
    name  text not null
);

create table if not exists food_portion (
    id                   bigint  primary key,
    food_id              bigint  not null references food (id) on delete cascade,
    amount               numeric,
    measure_unit_id      int     not null references measure_unit (id),
    portion_description  text,
    modifier             text,
    seq_num              int,
    gram_weight          numeric not null
);

create table if not exists food_image (
    id            bigint generated by default as identity primary key,
    food_id       bigint not null references food (id) on delete cascade,
    kind          text   not null check (kind in ('thumbnail', 'main')),
    storage_path  text,               -- key in the 'food-images' bucket
    external_url  text,
    width         int,
    height        int,
    attribution   text,
    -- true when the image was AI-generated (DALL-E, Imagen...). Keep
    -- accurate: generated food photos can mislead users about what a
    -- product looks like, and disclosure rules may require labeling.
    ai_generated  boolean not null default false,
    created_at    timestamptz not null default now(),
    check (num_nonnulls(storage_path, external_url) = 1)
);

-- ---------- 2b. Search: aliases & tags ------------------------

create table if not exists food_alias (
    id          bigint generated by default as identity primary key,
    food_id     bigint not null references food (id) on delete cascade,
    locale      text   not null,     -- BCP 47: de, hi-Latn...
    alias       text   not null,     -- Spaghetti, Garam Chai...
    source      text   not null default 'curated'
                check (source in ('curated', 'community', 'derived')),
    created_at  timestamptz not null default now(),
    unique (food_id, locale, alias)
);

create table if not exists tag (
    id    int generated by default as identity primary key,
    slug  text not null unique,      -- vegan, breakfast, high-protein...
    kind  text                       -- diet | allergen | meal_type | custom
);

create table if not exists food_tag (
    food_id  bigint not null references food (id) on delete cascade,
    tag_id   int    not null references tag (id) on delete cascade,
    source   text,                   -- curated | derived | community
    primary key (food_id, tag_id)
);

create table if not exists tag_translation (
    tag_id  int  not null references tag (id) on delete cascade,
    locale  text not null,
    name    text not null,           -- vegan -> Vegan, high-protein -> Proteinreich
    primary key (tag_id, locale)
);

-- ---------- 3. Localization ---------------------------------

create table if not exists food_translation (
    food_id       bigint not null references food (id) on delete cascade,
    locale        text   not null,    -- BCP 47: de, fr, es...
    description   text   not null,
    source        text   not null default 'machine'
                  check (source in ('native', 'machine', 'community', 'verified')),
    -- true when produced by MT/LLM (DeepL, GPT...). Stays true after a
    -- human review upgrades source to 'verified', preserving provenance;
    -- may also matter for EU AI Act style disclosure duties.
    ai_generated  boolean not null default false,
    updated_at    timestamptz not null default now(),
    primary key (food_id, locale)
);

create table if not exists food_category_translation (
    food_category_id  int  not null references food_category (id) on delete cascade,
    locale            text not null,
    description       text not null,
    primary key (food_category_id, locale)
);

create table if not exists food_portion_translation (
    food_portion_id  bigint not null references food_portion (id) on delete cascade,
    locale           text   not null,
    portion_description  text,
    modifier             text,
    -- Same provenance vocabulary as food_translation. Seeded machine output
    -- is not fit to show: the app displays only 'verified' rows and falls
    -- back to its own word for "serving" otherwise.
    source        text not null default 'machine'
                  check (source in ('native', 'machine', 'community', 'verified')),
    ai_generated  boolean not null default false,
    updated_at    timestamptz not null default now(),
    primary key (food_portion_id, locale)
);

create table if not exists measure_unit_translation (
    measure_unit_id  int  not null references measure_unit (id) on delete cascade,
    locale           text not null,
    name             text not null,
    -- Same provenance vocabulary as food_translation. Seeded machine output
    -- is not fit to show: the app is expected to display only 'verified'
    -- rows and fall back to its own word for "serving" otherwise.
    source        text not null default 'machine'
                  check (source in ('native', 'machine', 'community', 'verified')),
    ai_generated  boolean not null default false,
    updated_at    timestamptz not null default now(),
    primary key (measure_unit_id, locale)
);

-- ---------- 4. Source-specific side tables ------------------

create table if not exists bls_component (
    code             text primary key,   -- ENERCC, WATER, PROT625...
    name_de          text not null,
    name_en          text not null,
    unit             text not null,
    component_group  text,
    formula          text
);

create table if not exists market_acquisition (
    food_id            bigint primary key references food (id) on delete cascade,
    upc_code           text,
    brand_description  text
);

create table if not exists input_food (
    id             bigint  primary key,
    food_id        bigint  not null references food (id) on delete cascade,
    input_food_id  bigint  references food (id),
    gram_weight    numeric
);

create table if not exists food_component (
    id          bigint  primary key,
    food_id     bigint  not null references food (id) on delete cascade,
    name        text    not null,
    pct_weight  numeric,
    is_refuse   boolean not null
);

create table if not exists retention_factor (
    id           int  primary key,
    code         text not null,
    description  text not null
);

