-- ---------- 6b. App-facing search functions -----------------
-- The app calls these instead of filtering the view over the URL, so a
-- search term never reaches the API gateway log.
--
-- PostgREST turns a table query into a GET, which puts the term in the
-- query string; it issues an RPC as a POST with a JSON body. The gateway
-- log records `request.url` and `request.search` but has no body field, and
-- those URLs sit in the same record as the caller's IP, city, postal code,
-- ISP and TLS fingerprint. Removing that pairing is the whole point.
-- App issue simonoppowa/OpenNutriTracker#882.
--
-- Ranking stays in the app; what these decide is which hundred rows reach
-- it. Since 2026-09-12_search_rpc_order_by_portions.sql and
-- 2026-09-13_search_rpc_order_title_first.sql the pool is ordered: records
-- with a deliverable portion first (has_portion, stored on the view since
-- 2026-09-13_food_summary_has_portion.sql), then the records whose title —
-- the text before the first comma — is the term, then the shortest
-- description, then food_id. Without it a large family never reached the
-- app at all ("Potato, NFS" was rank 128 of 712 matches for potato). No
-- `ts_rank`: relevance among the hundred is the app's.

create or replace function search_food_summary(
    term      text,
    sources   text[] default null,
    max_rows  int    default 100
)
returns setof food_summary
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
    select fs.*
    from food_summary fs
    where to_tsvector('english', fs.name)
          @@ websearch_to_tsquery('english', term)
      and (sources is null or fs.source = any (sources))
    order by fs.has_portion desc,
             (lower(btrim(split_part(fs.name, ',', 1))) = lower(btrim(term))) desc,
             length(fs.name),
             fs.food_id
    limit greatest(max_rows, 0)
$$;

-- has_portion is the view's stored flag by a left join (coalesced to false;
-- every food_translation row has a summary row, and the FK to food keeps it
-- so), so the two hops of a localized search cannot disagree on it. A
-- database that still has the 39-column view and the three-column version
-- of this function needs 2026-09-13_food_summary_has_portion.sql, which
-- recreates both: CREATE OR REPLACE cannot change a return type, and IF NOT
-- EXISTS leaves the view as it is.
create or replace function search_food_translation(
    term      text,
    loc       text,
    max_rows  int default 100
)
returns table (food_id bigint, description text, source text, has_portion boolean)
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
    select ft.food_id, ft.description, ft.source,
           coalesce(fs.has_portion, false) as has_portion
    from food_translation ft
    left join food_summary fs on fs.food_id = ft.food_id
    where ft.locale = loc
      and to_tsvector('simple', ft.description)
          @@ websearch_to_tsquery('simple', term)
    order by coalesce(fs.has_portion, false) desc,
             (lower(btrim(split_part(ft.description, ',', 1))) = lower(btrim(term))) desc,
             length(ft.description),
             ft.food_id
    limit greatest(max_rows, 0)
$$;

-- The localized path needs a second hop: the app ranks the translation
-- matches itself and then fetches the summary rows for the ids that
-- survived. Those ids are derived from the term, so sending them as a
-- filter would put a fingerprint of the search back in the URL — which is
-- why this is an RPC too rather than a plain `in.(...)` query.
create or replace function food_summary_by_ids(
    ids      bigint[],
    sources  text[] default null
)
returns setof food_summary
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
    select fs.*
    from food_summary fs
    where fs.food_id = any (ids)
      and (sources is null or fs.source = any (sources))
$$;

-- ---------- 7. Row Level Security ---------------------------
-- Reference data: readable by everyone, writable only by service_role
-- (service_role bypasses RLS; no insert/update policies needed).

do $$
declare t text;
begin
    foreach t in array array[
        'food_source', 'food_category', 'food', 'nutrient',
        'nutrient_mapping', 'food_nutrient', 'measure_unit',
        'food_portion', 'food_image', 'food_translation',
        'food_category_translation', 'food_portion_translation',
        'measure_unit_translation', 'bls_component',
        'market_acquisition', 'input_food', 'food_component',
        'retention_factor', 'food_alias', 'tag', 'food_tag',
        'tag_translation'
    ] loop
        execute format('alter table %I enable row level security', t);
        execute format('drop policy if exists "public read" on %I', t);
        execute format(
            'create policy "public read" on %I for select to anon, authenticated using (true)', t);
    end loop;
end $$;

-- Materialized views have no RLS; restrict via grants instead.
revoke all on food_summary from anon, authenticated;
grant select on food_summary to anon, authenticated;

-- Functions are executable by PUBLIC on creation, so the grant is only
-- meaningful after the revoke.
-- A food's default portion label in the reader's language, and only when a
-- human has verified it. A function rather than a table read for the reason
-- the search functions are: a GET puts the food id in the gateway log beside
-- the caller's IP. The lateral pick mirrors food_summary's, so the label
-- describes the same portion its serving_gram_weight came from.
create or replace function portion_labels_by_food_ids(
    ids  bigint[],
    loc  text
)
returns table (food_id bigint, label text)
language sql
stable
as $$
    select f.id, t.portion_description
    from unnest(ids) as f(id)
    join lateral (
        select fp.id
        from food_portion fp
        where fp.food_id = f.id
        order by fp.seq_num nulls last, fp.id
        limit 1
    ) p on true
    join food_portion_translation t
      on t.food_portion_id = p.id
     and t.locale = loc
     and t.source = 'verified'
    where t.portion_description is not null
      and btrim(t.portion_description) <> '';
$$;

